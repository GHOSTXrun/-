import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join,dirname} from 'node:path';
import {Script} from 'node:vm';
const root=dirname(fileURLToPath(import.meta.url));
const read=file=>readFileSync(join(root,file),'utf8');
let html=read('index.html');
const engine=read('terminal-engine.mjs').replace(/^export /gm,'');
const app=read('unified.js').replace(/^import .*?;\r?\n/gm,'');
const script='const NightjarEngine=(()=>{'+engine+';return {createSession,settings,advance,fixture,validateCandidate,roles};})();\n(()=>{const {createSession,settings,advance,fixture,validateCandidate,roles}=NightjarEngine;'+app+'})();';
new Script(script,{filename:'nightjar-workspace.js'});
html=html.replace(/<link rel="stylesheet" href="\.\/(styles|integration)\.css[^\"]*">/g,(_,name)=>'<style>'+read(name+'.css')+'</style>');
html=html.replace(/<link[^>]*href="https:\/\/fonts\.googleapis\.com[^>]*>/g,'');
html=html.replace(/<script type="module" src="\.\/unified\.js"><\/script>/,()=>'<script>'+script.replace(/<\/script/gi,'<\\/script')+'</script>');
const favicon='data:image/svg+xml;base64,'+readFileSync(join(root,'assets/favicon.svg')).toString('base64');
html=html.replace(/\.\/assets\/favicon\.svg(?:\?[^\"]*)?/g,favicon);
html=html.replace('./assets/cellumo-logo.png','data:image/png;base64,'+readFileSync(join(root,'assets/cellumo-logo.png')).toString('base64'));
if(/<script[^>]*src=/.test(html)||/<link rel="stylesheet"/.test(html))throw Error('Standalone frontend still depends on external code');
writeFileSync(join(root,'frontend.html'),html);
mkdirSync(join(root,'dist'),{recursive:true});
writeFileSync(join(root,'dist/index.html'),html);
writeFileSync(join(root,'dist/.nojekyll'),'');
console.log('Built unified single-page workspace: frontend.html and dist/index.html');
